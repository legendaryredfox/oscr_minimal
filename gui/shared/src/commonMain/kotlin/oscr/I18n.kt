    private val tables = mapOf(Lang.PT to pt, Lang.EN to en, Lang.RU to ru, Lang.ZH to zh)

    fun t(lang: Lang, key: S): String = tables[lang]?.get(key) ?: en.getValue(key)

    /** A chave de texto de nome `name`, ou null se não existir (para montar chaves como ERR_DEV_4). */
    fun keyOrNull(name: String): S? = S.entries.firstOrNull { it.name == name }

    /** Texto com marcadores {0}, {1}... trocados pelos argumentos. */
    fun f(lang: Lang, key: S, vararg args: Any): String {
        var r = t(lang, key)
        args.forEachIndexed { i, a -> r = r.replace("{$i}", a.toString()) }
        return r
    }

    /** Idioma padrão a partir do locale do sistema (ex.: "pt_BR" -> PT, "ru_RU" -> RU, "zh_CN" -> ZH). */
    fun fromLocale(tag: String): Lang {
        val l = tag.lowercase()
        return when { l.startsWith("pt") -> Lang.PT; l.startsWith("ru") -> Lang.RU; l.startsWith("zh") -> Lang.ZH; else -> Lang.EN }
    }
